package JAVA_LIBRARY.Java_Lang.Number;

public class Lang_Boolean {

    public static void main (String[] args) {

        Boolean bool = false;

        double dod = Math.sqrt(169);

        if(dod != 12) {
            System.out.println(bool);
        } else {
            bool = true;
            System.out.println(bool + " " + Math.sqrt(144));
        }
    }
}